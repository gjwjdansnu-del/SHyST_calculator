#!/usr/bin/env python3
"""Generate the compact CoolProp gas-viscosity table used by the web app.

Reproduce with:
    python3 -m pip install CoolProp
    python3 generate-coolprop-viscosity-table.py

CoolProp is a build-time dependency only. The generated JavaScript table has
no runtime dependency and therefore also works on GitHub Pages.
"""

from pathlib import Path
import json

import CoolProp
from CoolProp.CoolProp import PhaseSI, PropsSI


TEMPERATURE_K = [67, 70, 80, 90, 100, 120, 150, 180, 200, 250, 300]
PRESSURE_PA = [10, 100, 1000, 5000, 10000]
FLUID = "Air.mix"
OUTPUT = Path(__file__).with_name("coolprop-viscosity-table.js")
GAS_PHASES = {"gas", "supercritical_gas"}


def build_table():
    values = []
    for temperature in TEMPERATURE_K:
        row = []
        for pressure in PRESSURE_PA:
            phase = PhaseSI("T", temperature, "P", pressure, FLUID)
            if phase not in GAS_PHASES:
                raise RuntimeError(
                    f"{FLUID} is not single-phase gas at T={temperature} K, "
                    f"p={pressure} Pa (CoolProp phase={phase})"
                )
            row.append(PropsSI("VISCOSITY", "T", temperature, "P", pressure, FLUID))
        values.append(row)

    return {
        "schemaVersion": 1,
        "source": "CoolProp",
        "coolPropVersion": CoolProp.__version__,
        "fluid": FLUID,
        "composition": "N2[0.7812]&Ar[0.0092]&O2[0.2096]",
        "phase": "single-phase gas only",
        "temperatureK": TEMPERATURE_K,
        "pressurePa": PRESSURE_PA,
        "viscosityPaS": values,
    }


def main():
    payload = json.dumps(build_table(), indent=2, ensure_ascii=True)
    text = (
        "// Generated by generate-coolprop-viscosity-table.py; do not edit by hand.\n"
        f"const SHYST_COOLPROP_VISCOSITY_TABLE = Object.freeze({payload});\n"
        "if (typeof globalThis !== 'undefined') {\n"
        "    globalThis.SHYST_COOLPROP_VISCOSITY_TABLE = "
        "SHYST_COOLPROP_VISCOSITY_TABLE;\n"
        "}\n"
        "if (typeof module !== 'undefined' && module.exports) {\n"
        "    module.exports = SHYST_COOLPROP_VISCOSITY_TABLE;\n"
        "}\n"
    )
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
